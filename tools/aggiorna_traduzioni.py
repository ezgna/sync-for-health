# Chiavi da non tradurre (simboli, formati numerici puri).
IGNORA = {"", "%", "%lld", "%@"}


def main():
    pattern = os.path.join(RADICE, "build/DD/Build/Intermediates.noindex/**/*.stringsdata")
    keys = set()
    for f in glob.glob(pattern, recursive=True):
        with open(f) as fh:
            for table in json.load(fh)["tables"].values():
                keys.update(e["key"] for e in table)
    if not keys:
        sys.exit("Nessun .stringsdata: esegui prima una build in build/DD.")
    strings = {}
    mancanti = []
    for k in sorted(keys):
        if k in IGNORA:
            strings[k] = {"shouldTranslate": False}
            continue
        loc = {"it": {"stringUnit": {"state": "translated", "value": k}}}
        if k in EN:
            loc["en"] = {"stringUnit": {"state": "translated", "value": EN[k]}}
        else:
            mancanti.append(k)
        strings[k] = {"localizations": loc}
    doc = {"sourceLanguage": "it", "strings": strings, "version": "1.0"}
    with open(USCITA, "w") as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=2, sort_keys=True)
        fh.write("\n")
    print(f"{len(strings)} chiavi scritte in {os.path.relpath(USCITA, RADICE)}")
    for k in mancanti:
        print(f"  manca la traduzione inglese: {k!r}")
    sys.exit(1 if mancanti else 0)


if __name__ == "__main__":
    main()
